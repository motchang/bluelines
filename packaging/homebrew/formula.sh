#!/usr/bin/env bash
# Prints the Homebrew formula for one blueline release.
#
#   packaging/homebrew/formula.sh <version> <SHA256SUMS>
#
# <version> is the release version without the leading `v` (for example
# 0.1.0). <SHA256SUMS> is the checksum file of that release, as the release
# workflow writes it: one `<sha256>  blueline-v<version>-<target>.tar.gz` line
# per target. The formula installs the prebuilt binary for the machine's OS and
# CPU from the GitHub Release; the release workflow pushes it to the
# motchang/homebrew-tap repository as Formula/blueline.rb.
set -euo pipefail

if [[ $# -ne 2 ]]; then
  echo "usage: $0 <version> <SHA256SUMS>" >&2
  exit 2
fi

version=$1
sums=$2

if [[ ! "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "error: version '$version' is not X.Y.Z (pre-releases are not published to the tap)" >&2
  exit 2
fi

base="https://github.com/motchang/bluelines/releases/download/v$version"

# Prints the url and sha256 lines for one target, indented for an on_* block.
asset() {
  local target=$1 file sha
  file="blueline-v$version-$target.tar.gz"
  sha=$(awk -v f="$file" '$2 == f || $2 == "*" f { print $1 }' "$sums")
  if [[ ! "$sha" =~ ^[0-9a-f]{64}$ ]]; then
    echo "error: no single SHA-256 for $file in $sums" >&2
    exit 1
  fi
  printf '      url "%s/%s"\n' "$base" "$file"
  printf '      sha256 "%s"\n' "$sha"
}

# Command substitution runs in a subshell, so check each one: `exit` in asset()
# would otherwise only end that subshell.
mac_arm=$(asset aarch64-apple-darwin)
mac_intel=$(asset x86_64-apple-darwin)
linux_arm=$(asset aarch64-unknown-linux-musl)
linux_intel=$(asset x86_64-unknown-linux-musl)

cat <<EOF
# This file is generated by the release workflow of motchang/bluelines
# (packaging/homebrew/formula.sh). Edit it there, not here.
class Blueline < Formula
  desc "Preview markdown, mermaid included, in a browser tab that reloads on save"
  homepage "https://github.com/motchang/bluelines"
  version "$version"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
$mac_arm
    end
    on_intel do
$mac_intel
    end
  end

  on_linux do
    on_arm do
$linux_arm
    end
    on_intel do
$linux_intel
    end
  end

  def install
    bin.install "blueline"
  end

  test do
    assert_equal "blueline #{version}", shell_output("#{bin}/blueline --version").strip
  end
end
EOF
